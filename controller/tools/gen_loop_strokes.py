"""Generate the strokes made from simulated chaotic systems:

  main/stroke_pendulum_table.h  "Pendulum": a double pendulum's lower bob swinging side to side
  main/stroke_lorenz_table.h    "Lorenz":   the Lorenz system's x, circling one lobe, then the other

Chaotic motion never repeats, so a stretch of each is made into a seamless loop: over its first
FADE_S seconds it cross-fades from the run just past the loop's end, so the end runs straight on
into the beginning. The loop then starts at its lowest point and is scaled 0..1, so the stroke
starts at zero offset like the others. The controller interpolates between the RATE_HZ samples
(loop_stroke_eval in strokes.c).

Run from controller/ after changing the settings below (numpy only):

    python3 tools/gen_loop_strokes.py
"""
import os

import numpy as np

FADE_S = 1.5        # cross-fade at the join
RATE_HZ = 50        # table samples per second
SIM_DT = 0.001      # integration step
MAIN = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'main')


def rk4(deriv, state, steps, dt, out):
    """Integrate, recording out(state) before each step."""
    s = np.array(state, dtype=float)
    rec = np.empty(steps)
    for i in range(steps):
        rec[i] = out(s)
        k1 = deriv(s)
        k2 = deriv(s + dt / 2 * k1)
        k3 = deriv(s + dt / 2 * k2)
        k4 = deriv(s + dt * k3)
        s = s + dt / 6 * (k1 + 2 * k2 + 2 * k3 + k4)
    return rec


# --- Pendulum: two equal arms and masses, released from rest -----------------------------------
PENDULUM_ARM_M = 0.25                                # sets the pace: about one swing a second
PENDULUM_THETA = (3 * np.pi / 7, 3 * np.pi / 4)      # starting angles, as in ~/dev/doublependulum/dp.py
PENDULUM_LOOP_S = 20.0
G = 9.81


def pendulum(seconds):
    """Lower bob's sideways position every SIM_DT seconds."""
    L = PENDULUM_ARM_M

    def deriv(s):
        t1, w1, t2, w2 = s
        c, sn = np.cos(t1 - t2), np.sin(t1 - t2)
        a1 = (G * np.sin(t2) * c - sn * (L * w1 ** 2 * c + L * w2 ** 2) - 2 * G * np.sin(t1)) / L / (1 + sn ** 2)
        a2 = (2 * (L * w1 ** 2 * sn - G * np.sin(t2) + G * np.sin(t1) * c) + L * w2 ** 2 * sn * c) / L / (1 + sn ** 2)
        return np.array([w1, a1, w2, a2])

    return rk4(deriv, [PENDULUM_THETA[0], 0, PENDULUM_THETA[1], 0], int(round(seconds / SIM_DT)), SIM_DT,
               lambda s: L * np.sin(s[0]) + L * np.sin(s[2]))


# --- Lorenz: the classic system (sigma 10, rho 28, beta 8/3), its x -----------------------------
LORENZ_S_PER_UNIT = 1.0     # seconds per unit of Lorenz time: sets the pace (about a swing a second)
LORENZ_SKIP_UNITS = 20.0    # let it settle onto the attractor first
LORENZ_LOOP_S = 24.0


def lorenz(seconds):
    """x every SIM_DT seconds, after the settling time."""
    def deriv(s):
        x, y, z = s
        return np.array([10.0 * (y - x), x * (28.0 - z) - y, x * y - 8.0 / 3.0 * z])

    dt = SIM_DT / LORENZ_S_PER_UNIT   # Lorenz time per output step
    skip = int(round(LORENZ_SKIP_UNITS / dt))
    x = rk4(deriv, [1.0, 1.0, 1.0], skip + int(round(seconds / SIM_DT)), dt, lambda s: s[0])
    return x[skip:]


def make_loop(signal, loop_s):
    """A seamless loop_s loop from a run at least loop_s + FADE_S long, sampled every SIM_DT."""
    t = np.arange(len(signal)) * SIM_DT
    tt = np.arange(0, loop_s, SIM_DT)
    w = np.clip(tt / FADE_S, 0, 1)
    w = 0.5 - 0.5 * np.cos(np.pi * w)                    # 0 -> 1, smoothly
    loop = w * np.interp(tt, t, signal) + (1 - w) * np.interp(tt + loop_s, t, signal)
    loop = np.roll(loop, -int(np.argmin(loop)))         # start at the lowest point
    return (loop - loop.min()) / (loop.max() - loop.min())


def write_table(name, upper, loop, description):
    speed = np.abs(np.diff(np.append(loop, loop[0]))) / SIM_DT
    print(f'{name}: peak speed {speed.max():.2f} stroke lengths/s at real time; '
          f'jump at the join {abs(loop[-1] - loop[0]):.5f}')
    step = int(round(1 / (RATE_HZ * SIM_DT)))
    samples = np.round(loop[::step] * 32767).astype(int)
    lines = [
        '// SPDX-FileCopyrightText: 2026 MattEdm',
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        f"// GENERATED by tools/gen_loop_strokes.py: the \"{name}\" stroke. Don't edit; regenerate.",
    ] + [f'// {line}' for line in description] + [
        '#pragma once',
        '',
        '#include <stdint.h>',
        '',
        f'#define {upper}_RATE_HZ {RATE_HZ}',
        f'#define {upper}_SAMPLES {len(samples)}',
        f'static const uint16_t {name.lower()}_samples[{upper}_SAMPLES] = {{',
    ]
    for i in range(0, len(samples), 16):
        lines.append('    ' + ', '.join(str(v) for v in samples[i:i + 16]) + ',')
    lines += ['};', '']
    path = os.path.join(MAIN, f'stroke_{name.lower()}_table.h')
    with open(path, 'w') as f:
        f.write('\n'.join(lines))
    print(f'  {path}: {len(samples)} samples at {RATE_HZ} Hz')


def main():
    write_table('Pendulum', 'PENDULUM', make_loop(pendulum(PENDULUM_LOOP_S + FADE_S + 0.1), PENDULUM_LOOP_S), [
        f'Double pendulum, arms {PENDULUM_ARM_M} m, released from {PENDULUM_THETA[0]:.4f} and {PENDULUM_THETA[1]:.4f} rad: the lower',
        f"bob's sideways position as a seamless {PENDULUM_LOOP_S:g} s loop, 0..32767, starting at its lowest.",
    ])
    write_table('Lorenz', 'LORENZ', make_loop(lorenz(LORENZ_LOOP_S + FADE_S + 0.1), LORENZ_LOOP_S), [
        f'Lorenz system (10, 28, 8/3) x, {LORENZ_S_PER_UNIT} s per unit of its time: a seamless',
        f'{LORENZ_LOOP_S:g} s loop, 0..32767, starting at its lowest.',
    ])


if __name__ == '__main__':
    main()

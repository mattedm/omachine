"""Generate main/stroke_pendulum_table.h: the "Pendulum" stroke.

A double pendulum (two equal arms and masses, released from rest) is simulated and the lower
bob's sideways position becomes the stroke. Its motion is chaotic and never repeats, so a
LOOP_S stretch is made into a seamless loop: over its first FADE_S seconds it cross-fades from
the run just past the loop's end, so the end runs straight on into the beginning. The loop then
starts at its lowest point and is scaled 0..1, so the stroke starts at zero offset like the
others. The controller interpolates between the RATE_HZ samples.

Run from controller/ after changing the settings below (numpy only):

    python3 tools/gen_pendulum_stroke.py
"""
import os

import numpy as np

ARM_M = 0.25                           # arm length: sets the pace, about one swing a second
THETA1, THETA2 = 3 * np.pi / 7, 3 * np.pi / 4   # starting angles (rad), as in ~/dev/doublependulum/dp.py
LOOP_S = 20.0                          # loop length
FADE_S = 1.5                           # cross-fade at the join
RATE_HZ = 50                           # table samples per second
SIM_DT = 0.001                         # integration step (s)
G = 9.81

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'main', 'stroke_pendulum_table.h')


def simulate(seconds):
    """Lower bob's sideways position every SIM_DT, by RK4 (equal masses and arms)."""
    L = ARM_M

    def deriv(s):
        t1, w1, t2, w2 = s
        c, sn = np.cos(t1 - t2), np.sin(t1 - t2)
        a1 = (G * np.sin(t2) * c - sn * (L * w1 ** 2 * c + L * w2 ** 2) - 2 * G * np.sin(t1)) / L / (1 + sn ** 2)
        a2 = (2 * (L * w1 ** 2 * sn - G * np.sin(t2) + G * np.sin(t1) * c) + L * w2 ** 2 * sn * c) / L / (1 + sn ** 2)
        return np.array([w1, a1, w2, a2])

    s = np.array([THETA1, 0.0, THETA2, 0.0])
    n = int(round(seconds / SIM_DT))
    x = np.empty(n)
    for i in range(n):
        x[i] = L * np.sin(s[0]) + L * np.sin(s[2])
        k1 = deriv(s)
        k2 = deriv(s + SIM_DT / 2 * k1)
        k3 = deriv(s + SIM_DT / 2 * k2)
        k4 = deriv(s + SIM_DT * k3)
        s = s + SIM_DT / 6 * (k1 + 2 * k2 + 2 * k3 + k4)
    return x


def main():
    x = simulate(LOOP_S + FADE_S + 0.1)
    t = np.arange(len(x)) * SIM_DT
    tt = np.arange(0, LOOP_S, SIM_DT)
    w = np.clip(tt / FADE_S, 0, 1)
    w = 0.5 - 0.5 * np.cos(np.pi * w)                    # 0 -> 1, smoothly
    loop = w * np.interp(tt, t, x) + (1 - w) * np.interp(tt + LOOP_S, t, x)
    loop = np.roll(loop, -int(np.argmin(loop)))         # start at the lowest point
    loop = (loop - loop.min()) / (loop.max() - loop.min())

    speed = np.abs(np.diff(np.append(loop, loop[0]))) / SIM_DT
    print(f'peak speed {speed.max():.2f} stroke lengths/s at real time; '
          f'jump at the join {abs(loop[-1] - loop[0]):.5f}')

    step = int(round(1 / (RATE_HZ * SIM_DT)))
    samples = np.round(loop[::step] * 32767).astype(int)
    lines = [
        '// SPDX-FileCopyrightText: 2026 MattEdm',
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        "// GENERATED by tools/gen_pendulum_stroke.py: the \"Pendulum\" stroke. Don't edit; regenerate.",
        f'// Double pendulum, arms {ARM_M} m, released from {THETA1:.4f} and {THETA2:.4f} rad: the lower',
        f'// bob\'s sideways position as a seamless {LOOP_S:g} s loop, 0..32767, starting at its lowest.',
        '#pragma once',
        '',
        '#include <stdint.h>',
        '',
        f'#define PENDULUM_RATE_HZ {RATE_HZ}',
        f'#define PENDULUM_SAMPLES {len(samples)}',
        'static const uint16_t pendulum_samples[PENDULUM_SAMPLES] = {',
    ]
    for i in range(0, len(samples), 16):
        lines.append('    ' + ', '.join(str(v) for v in samples[i:i + 16]) + ',')
    lines += ['};', '']
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines))
    print(f'{OUT}: {len(samples)} samples at {RATE_HZ} Hz')


if __name__ == '__main__':
    main()
